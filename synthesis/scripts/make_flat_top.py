#!/usr/bin/env python3
"""Generate a structural flat external-port wrapper; functional RTL is unchanged."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
from axi_ports import WIDTHS as widths, MANAGER_OUTPUTS as manager_outputs
s='''// Generated by synthesis/scripts/make_flat_top.py; no RAM or demo adapter.
module axi_fabric_flat #(
    parameter int NM=2,NS=2,ADDR_W=32,DATA_W=64,ID_W=4,
    parameter int MAX_OUTSTANDING=4,S_ADDR_WIDTH=16,
    parameter bit TARGET_PIPELINE=0,
    parameter logic [ADDR_W-1:0] BASE_ADDR='0
)(
    input logic ACLK,ARESETn,
'''
ports=[]
for side,count in [('m','NM'),('s','NS')]:
 for sig,w in widths.items():
  is_input=(sig in manager_outputs)==(side=='m')
  ports.append(f'    {"input" if is_input else "output"} logic [{count}-1:0]'+('' if w=='1' else f'[{w}-1:0]')+f' {side}_{sig}')
s+=',\n'.join(ports)+'\n);\n'
for side,count in [('m','NM'),('s','NS')]:
 s+=f'    axi_if #(.ADDR_W(ADDR_W),.DATA_W(DATA_W),.ID_W(ID_W)) {side}_axi[{count}](.ACLK,.ARESETn);\n'
 s+=f'    for(genvar i=0;i<{count};i++) begin : g_{side}\n'
 for sig in widths:
  left,right=f'{side}_axi[i].{sig}',f'{side}_{sig}[i]'
  if (sig in manager_outputs)!=(side=='m'):left,right=right,left
  s+=f'        assign {left}={right};\n'
 s+='    end\n'
s+='''    axi_interconnect #(.NM(NM),.NS(NS),.ADDR_W(ADDR_W),.DATA_W(DATA_W),.ID_W(ID_W),
        .MAX_OUTSTANDING(MAX_OUTSTANDING),.TARGET_PIPELINE(TARGET_PIPELINE),.S_ADDR_WIDTH(S_ADDR_WIDTH),.BASE_ADDR(BASE_ADDR))
        dut(.ACLK,.ARESETn,.m_axi,.s_axi);
endmodule
'''
(ROOT/'build').mkdir(exist_ok=True)
(ROOT/'build/axi_fabric_flat.sv').write_text(s)
